import type { ParityRow, ParitySurface } from "@/lib/core/parity"

const y = (how: string, ref?: string): ParitySurface => ({ how, status: "Y", ref })
const p = (how: string, ref?: string): ParitySurface => ({ how, status: "P", ref })
const n = (how: string, ref?: string): ParitySurface => ({ how, status: "N", ref })
const host = (how: string, ref?: string): ParitySurface => ({ how, status: "host", ref })
const na = (how: string): ParitySurface => ({ how, status: "n/a" })

function row(
  id: string,
  window: string,
  gui: { label: string; file: string; how?: string },
  tui: ParitySurface,
  api: ParitySurface,
  mcp: ParitySurface,
  library: ParitySurface,
): ParityRow {
  return {
    id,
    window,
    gui: { label: gui.label, file: gui.file, how: gui.how ?? gui.label, status: "Y" },
    tui,
    api,
    mcp,
    library,
  }
}

