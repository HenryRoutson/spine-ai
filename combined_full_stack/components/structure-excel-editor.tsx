"use client"

import { Plus, Trash2, Lock, Sparkles, AlertTriangle } from "lucide-react"
import { useStore, uid } from "@/lib/store"
import {
  type FieldType,
  type ModelField,
  type StructureModel,
} from "@/lib/types"
import { isLockedStructureModel } from "@/lib/structure"
import { StructureFieldRefPicker, isRefFieldType } from "@/components/structure-field-ref-picker"
import { modelsForRefPicker } from "@/lib/structure-ref"
import { FIELD_TYPE_OPTIONS, fieldTypeLabel } from "@/lib/structure-field-labels"
import { Button } from "@/components/ui/button"
import { WARNING_TEXT_CLASS } from "@/lib/ui-classes"
import { cn } from "@/lib/utils"

const REF_TYPES: FieldType[] = ["model", "list[model]"]

type StructureExcelEditorProps = {
  selectedId: string
  onSelectId: (id: string) => void
}

export function StructureExcelEditor({ selectedId, onSelectId }: StructureExcelEditorProps) {
  const { models, setModels } = useStore()
  const selected = models.find((m) => m.id === selectedId) ?? models[0]
  const selectedLocked = selected ? isLockedStructureModel(selected) : false

  function updateModel(next: StructureModel) {
    if (isLockedStructureModel(next)) return
    setModels(models.map((m) => (m.id === next.id ? next : m)))
  }

  function addModel() {
    const m: StructureModel = {
      id: uid(),
      name: "NewModel",
      description: "",
      fields: [{ id: uid(), name: "field", type: "text", optional: false, description: "" }],
    }
    setModels([...models, m])
    onSelectId(m.id)
  }

  function deleteModel(id: string) {
    const target = models.find((m) => m.id === id)
    if (target && isLockedStructureModel(target)) return
    const next = models.filter((m) => m.id !== id)
    setModels(next)
    if (selectedId === id) onSelectId(next[0]?.id ?? "")
  }

  function addField() {
    if (!selected) return
    updateModel({
      ...selected,
      fields: [
        ...selected.fields,
        { id: uid(), name: "field", type: "text", optional: false, description: "" },
      ],
    })
  }

  function updateField(fieldId: string, patch: Partial<ModelField>) {
    if (!selected) return
    updateModel({
      ...selected,
      fields: selected.fields.map((f) => (f.id === fieldId ? { ...f, ...patch } : f)),
    })
  }

  function removeField(fieldId: string) {
    if (!selected) return
    updateModel({
      ...selected,
      fields: selected.fields.filter((f) => f.id !== fieldId),
    })
  }

  if (!selected) {
    return (
      <div className="flex flex-1 items-center justify-center">
        <p className="text-xs text-muted-foreground">No structure selected — add one below.</p>
      </div>
    )
  }

  return (
    <div className="flex min-w-0 flex-1 flex-col overflow-hidden bg-[oklch(0.16_0.004_264)]">
      {/* AI : model title row — spreadsheet header band */}
      <div className="shrink-0 border-b border-border bg-secondary/30 px-4 py-3">
        {selectedLocked && (
          <div className="mb-2 flex items-center gap-2 text-[11px] text-muted-foreground">
            <Lock className="h-3.5 w-3.5" />
            Built-in structure — read only
          </div>
        )}
        {selected.auto && (
          <div className="mb-2 flex items-center gap-2 text-[11px] text-chart-3">
            <Sparkles className="h-3.5 w-3.5" />
            Auto-generated by a pipeline step
          </div>
        )}
        {selected.fields.length === 0 && (
          <div className={cn("mb-2 flex items-center gap-2 text-[11px]", WARNING_TEXT_CLASS)}>
            <AlertTriangle className="h-3.5 w-3.5 shrink-0" />
            Add at least one row before using this structure in a pipeline
          </div>
        )}
        <div className="flex items-start gap-3">
          <div className="min-w-0 flex-1 space-y-1">
            <input
              value={selected.name}
              onChange={(e) => updateModel({ ...selected, name: e.target.value })}
              readOnly={selectedLocked}
              placeholder="Structure name"
              className="w-full border-0 bg-transparent text-sm font-semibold text-foreground outline-none placeholder:text-muted-foreground read-only:cursor-default"
            />
            <input
              value={selected.description}
              onChange={(e) => updateModel({ ...selected, description: e.target.value })}
              readOnly={selectedLocked}
              placeholder="What does this structure represent?"
              className="w-full border-0 bg-transparent text-xs text-muted-foreground outline-none placeholder:text-muted-foreground/70 read-only:cursor-default"
            />
          </div>
          {models.length > 1 && !selectedLocked && (
            <Button
              size="icon"
              variant="ghost"
              className="h-8 w-8 shrink-0 text-muted-foreground hover:text-destructive"
              onClick={() => deleteModel(selected.id)}
            >
              <Trash2 className="h-4 w-4" />
            </Button>
          )}
        </div>
      </div>

      {/* AI : spreadsheet grid */}
      <div className="min-h-0 flex-1 overflow-auto">
        <table className="w-full min-w-[720px] border-collapse text-[11.5px]">
          <thead className="sticky top-0 z-10">
            <tr className="bg-secondary/80 backdrop-blur-sm">
              <th className="w-9 border-b border-r border-border px-1 py-1.5 text-center text-[10px] font-medium text-muted-foreground">
                #
              </th>
              <th className="min-w-[140px] border-b border-r border-border px-2 py-1.5 text-left text-[10px] font-medium uppercase tracking-wide text-muted-foreground">
                Field name
              </th>
              <th className="min-w-[150px] border-b border-r border-border px-2 py-1.5 text-left text-[10px] font-medium uppercase tracking-wide text-muted-foreground">
                Data type
              </th>
              <th className="min-w-[180px] border-b border-r border-border px-2 py-1.5 text-left text-[10px] font-medium uppercase tracking-wide text-muted-foreground">
                Description
              </th>
              <th className="min-w-[120px] border-b border-r border-border px-2 py-1.5 text-left text-[10px] font-medium uppercase tracking-wide text-muted-foreground">
                Example
              </th>
              <th className="w-20 border-b border-r border-border px-2 py-1.5 text-center text-[10px] font-medium uppercase tracking-wide text-muted-foreground">
                Required
              </th>
              <th className="w-10 border-b border-border px-1 py-1.5" />
            </tr>
          </thead>
          <tbody>
            {selected.fields.map((f, rowIdx) => (
              <FieldRow
                key={f.id}
                field={f}
                fields={selected.fields}
                rowIdx={rowIdx}
                locked={selectedLocked}
                models={models}
                selectedId={selected.id}
                onUpdate={(patch) => updateField(f.id, patch)}
                onRemove={() => removeField(f.id)}
              />
            ))}
          </tbody>
        </table>

        {!selectedLocked && (
          <div className="border-t border-border px-3 py-2">
            <Button variant="ghost" size="sm" className="h-7 text-xs" onClick={addField}>
              <Plus className="mr-1 h-3.5 w-3.5" /> Add row
            </Button>
          </div>
        )}
      </div>

      {/* AI : sheet tabs — one tab per structure model */}
      <div className="flex shrink-0 items-end gap-0 overflow-x-auto border-t border-border bg-secondary/20 px-1 pt-1">
        {models.map((m) => (
          <button
            key={m.id}
            onClick={() => onSelectId(m.id)}
            className={cn(
              "relative shrink-0 rounded-t border border-b-0 px-3 py-1.5 text-[11px] transition-colors",
              m.id === selected.id
                ? "z-[1] -mb-px border-border bg-[oklch(0.16_0.004_264)] font-medium text-foreground"
                : "border-transparent bg-secondary/40 text-muted-foreground hover:bg-secondary/70 hover:text-foreground",
            )}
          >
            {m.name}
            {isLockedStructureModel(m) && <Lock className="ml-1 inline h-2.5 w-2.5 opacity-60" />}
          </button>
        ))}
        {!selectedLocked && (
          <button
            onClick={addModel}
            className="mb-0.5 ml-1 shrink-0 rounded px-2 py-1 text-[11px] text-muted-foreground hover:bg-secondary/60 hover:text-foreground"
          >
            <Plus className="inline h-3 w-3" />
          </button>
        )}
      </div>
    </div>
  )
}

type FieldRowProps = {
  field: ModelField
  fields: ModelField[]
  rowIdx: number
  locked: boolean
  models: StructureModel[]
  selectedId: string
  onUpdate: (patch: Partial<ModelField>) => void
  onRemove: () => void
}

function FieldRow({ field, fields, rowIdx, locked, models, selectedId, onUpdate, onRemove }: FieldRowProps) {
  const stripe = rowIdx % 2 === 1
  const refModels = modelsForRefPicker(models, selectedId, fields)

  return (
    <>
      <tr className={cn("group", stripe && "bg-secondary/15")}>
        <td className="border-b border-r border-border bg-secondary/25 px-1 py-0 text-center text-[10px] text-muted-foreground">
          {rowIdx + 1}
        </td>
        <td className="border-b border-r border-border p-0">
          <CellInput
            value={field.name}
            onChange={(v) => onUpdate({ name: v })}
            placeholder="e.g. Company name"
            locked={locked}
          />
        </td>
        <td className="border-b border-r border-border p-0 align-top">
          <div className="space-y-0.5 px-1 py-1">
            <select
              value={field.type}
              onChange={(e) => {
                const type = e.target.value as FieldType
                onUpdate({
                  type,
                  ref: REF_TYPES.includes(type) ? refModels[0]?.id : undefined,
                })
              }}
              disabled={locked}
              className="h-7 w-full border-0 bg-transparent px-1 text-[11.5px] outline-none disabled:cursor-default disabled:opacity-70"
            >
              {FIELD_TYPE_OPTIONS.map(({ value, label }) => (
                <option key={value} value={value}>
                  {label}
                </option>
              ))}
            </select>
            {isRefFieldType(field.type) && (
              <StructureFieldRefPicker
                field={field}
                fields={fields}
                models={models}
                selectedId={selectedId}
                locked={locked}
                onRefChange={(ref) => onUpdate({ ref })}
                compact
              />
            )}
          </div>
        </td>
        <td className="border-b border-r border-border p-0">
          <CellInput
            value={field.description}
            onChange={(v) => onUpdate({ description: v })}
            placeholder="What should go here?"
            locked={locked}
          />
        </td>
        <td className="border-b border-r border-border p-0">
          <CellInput
            value={field.example ?? ""}
            onChange={(v) => onUpdate({ example: v || undefined })}
            placeholder="Sample value"
            locked={locked}
            mono
          />
        </td>
        <td className="border-b border-r border-border p-0 text-center">
          <button
            type="button"
            disabled={locked}
            onClick={() => onUpdate({ optional: !field.optional })}
            className={cn(
              "mx-auto flex h-6 w-14 items-center justify-center rounded text-[10px] font-medium transition-colors",
              field.optional
                ? "bg-secondary text-muted-foreground"
                : "bg-primary/15 text-primary",
              locked && "cursor-default opacity-70",
            )}
          >
            {field.optional ? "Optional" : "Required"}
          </button>
        </td>
        <td className="border-b border-border p-0 text-center">
          {!locked && (
            <button
              type="button"
              onClick={onRemove}
              className="px-1 text-muted-foreground opacity-0 transition-opacity hover:text-destructive group-hover:opacity-100"
            >
              <Trash2 className="h-3.5 w-3.5" />
            </button>
          )}
        </td>
      </tr>
      {field.type === "json" && (
        <tr className={cn(stripe && "bg-secondary/15")}>
          <td className="border-b border-r border-border bg-secondary/25" />
          <td colSpan={6} className="border-b border-border px-2 py-1 text-[10px] text-amber-700 dark:text-amber-500">
            Flexible data stores anything — prefer &ldquo;{fieldTypeLabel("model")}&rdquo; when you can define a shape.
          </td>
        </tr>
      )}
    </>
  )
}

function CellInput({
  value,
  onChange,
  placeholder,
  locked,
  mono,
}: {
  value: string
  onChange: (v: string) => void
  placeholder?: string
  locked: boolean
  mono?: boolean
}) {
  return (
    <input
      value={value}
      onChange={(e) => onChange(e.target.value)}
      readOnly={locked}
      placeholder={placeholder}
      className={cn(
        "h-8 w-full border-0 bg-transparent px-2 text-[11.5px] outline-none placeholder:text-muted-foreground/50 read-only:cursor-default",
        mono && "font-mono",
      )}
    />
  )
}
