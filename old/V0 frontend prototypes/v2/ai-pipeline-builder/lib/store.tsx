interface StoreState {
  projects: Project[]
  activeProjectId: string
  setActiveProjectId: (id: string) => void
  addProject: () => void
  project: Project
  // shortcuts that read/write the active project
  models: StructureModel[]
  setModels: (m: StructureModel[]) => void
  modules: PipelineModule[]
  setModules: (m: PipelineModule[]) => void
  strategies: Strategy[]
  setStrategies: (s: Strategy[]) => void
  // global model
  model: string
  setModel: (m: string) => void
  // documents
  docs: DocRef[]
  addDoc: (name: string, type: InputType, content: string, label: DocLabel) => DocRef
  // runs / logs
  runs: PipelineRun[]
  addRun: (r: PipelineRun) => void
  // billing
  billing: BillingPoint[]
}

const StoreContext = createContext<StoreState | null>(null)

export function StoreProvider({ children }: { children: ReactNode }) {
  const [projects, setProjects] = useState<Project[]>([legalProject, blankProject])
  const [activeProjectId, setActiveProjectId] = useState("p_legal")
  const [model, setModel] = useState(DEFAULT_MODEL)
  const [docs, setDocs] = useState<DocRef[]>(initialDocs)
  const [runs, setRuns] = useState<PipelineRun[]>([])

  const project = useMemo(
    () => projects.find((p) => p.id === activeProjectId) ?? projects[0],
    [projects, activeProjectId],
  )

  const patchProject = useCallback(
    (patch: Partial<Project>) => {
      setProjects((prev) =>
        prev.map((p) => (p.id === activeProjectId ? { ...p, ...patch } : p)),
      )
    },
    [activeProjectId],
  )

  const addProject = useCallback(() => {
    const id = "p_" + uid()
    const fresh: Project = {
      ...blankProject,
      id,
      name: "Untitled Pipeline",
      modules: blankProject.modules.map((m) => ({ ...m, id: uid() })),
      strategies: blankProject.strategies.map((s) => ({ ...s, id: uid() })),
    }
    setProjects((prev) => [...prev, fresh])
    setActiveProjectId(id)
  }, [])

  const addDoc = useCallback(
    (name: string, type: InputType, content: string, label: DocLabel) => {
      const id = hashContent(content)
      const existing = docs.find((d) => d.id === id)
      if (existing) return existing
      const doc: DocRef = {
        id,
        name,
        type,
        label,
        sizeKb: Math.max(1, Math.round(content.length / 10)),
        uploadedAt: Date.now(),
        preview: content.slice(0, 180),
      }
      setDocs((prev) => [doc, ...prev])
      return doc
    },
    [docs],
  )

  const addRun = useCallback((r: PipelineRun) => {
    setRuns((prev) => [r, ...prev].slice(0, 50))
  }, [])

  const value: StoreState = {
    projects,
    activeProjectId,
    setActiveProjectId,
    addProject,
    project,
    models: project.models,
    setModels: (m) => patchProject({ models: m }),
    modules: project.modules,
    setModules: (m) => patchProject({ modules: m }),
    strategies: project.strategies,
    setStrategies: (s) => patchProject({ strategies: s }),
    model,
    setModel,
    docs,
    addDoc,
    runs,
    addRun,
    billing: billingSeries,
  }

  return <StoreContext.Provider value={value}>{children}</StoreContext.Provider>
}

export function useStore() {
  const ctx = useContext(StoreContext)
  if (!ctx) throw new Error("useStore must be used within StoreProvider")
  return ctx
}

